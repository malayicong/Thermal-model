"""
Layer-by-layer thermal spikes for Vibenite 290 EBM builds.

Simulates a hatch patch of one layer around a probe column and records
T(t) at depths below the surface.  A probe at depth n * layer_thickness
sees the spike a material point receives when the n-th layer above it is
melted, so one layer simulation gives the whole sequence of re-heating
spikes (assuming every layer is scanned the same way).

For each process scenario this script writes
    inputs/vibenite290/config_<name>.yaml      (reproducible model input)
    inputs/vibenite290/path_<name>.csv
    Data/vibenite290/<name>_T_history.csv       (time_s, T at every depth)
    Data/vibenite290/<name>_spikes.csv          (per-layer spike summary)
and prints melt depth, number of remelted layers and cooling rates.

Usage:
    python tools/vibenite290_layer_history.py              # all scenarios
    python tools/vibenite290_layer_history.py ref A_speed  # selected ones
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.config_reader import load_config          # noqa: E402
from src.integration import Integrator, calc_temperature  # noqa: E402

TEMPLATE = ROOT / "inputs" / "config_Vibenite290.yaml"
CFG_DIR  = ROOT / "inputs" / "vibenite290"
OUT_DIR  = ROOT / "Data" / "vibenite290"

LAYER_T   = 0.16e-3     # m   layer thickness
LINE_LEN  = 30.0        # mm  hatch length = part diameter
PATCH_HW  = 3.0         # mm  half-width of simulated hatch patch (in y)
T_AFTER   = 2.0         # s   cooling time simulated after the patch
DZ_FINE   = 20e-6       # m   depth spacing used to locate the melt-pool bottom
Z_MAX     = 1.0e-3      # m   deepest probe

# Operator-recommended: 273 W, 122 mm/s, 0.2 mm -> 70 J/mm^3.
# The studied batch has VED ~36 J/mm^3; which parameter changed is unknown,
# so the three ways of halving VED are simulated.
SCENARIOS = {
    "ref":      dict(power=273.0, speed=122.0, offset=0.20,
                     note="recommended, VED 70 J/mm3"),
    "A_speed":  dict(power=273.0, speed=237.0, offset=0.20,
                     note="VED 36: higher speed"),
    "B_power":  dict(power=140.0, speed=122.0, offset=0.20,
                     note="VED 36: lower power (~2.3 mA)"),
    "C_offset": dict(power=273.0, speed=122.0, offset=0.39,
                     note="VED 36: larger line offset"),
}


def ved(s: dict) -> float:
    return s["power"] / (s["speed"] * s["offset"] * LAYER_T * 1e3)


def hatch_rows(speed_mm_s: float, offset_mm: float) -> list[list[float]]:
    """Snake hatch along x, centred on the probe column at (0, 0)."""
    v = speed_mm_s * 1e-3
    n_half = int(np.floor(PATCH_HW / offset_mm))
    ys = [i * offset_mm for i in range(-n_half, n_half + 1)]
    x0, x1 = -LINE_LEN / 2, LINE_LEN / 2
    rows = [[1, x0, ys[0], 0, 0, 1.0e-4]]
    for i, y in enumerate(ys):
        xs, xe = (x0, x1) if i % 2 == 0 else (x1, x0)
        if i > 0:
            rows.append([0, xs, y, 0, 1, v])      # step over to next line
        rows.append([0, xe, y, 0, 1, v])
    rows.append([1, rows[-1][1], ys[-1], 0, 0, 1.0e-4])
    return rows


def write_scenario_files(name: str, s: dict) -> Path:
    cfg = yaml.safe_load(TEMPLATE.read_text(encoding="utf-8"))
    cfg["simulation"]["name"] = f"EBM_Vibenite290_{name}"
    cfg["beam"]["power"] = s["power"]

    path_file = CFG_DIR / f"path_{name}.csv"
    with open(path_file, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["mode", "x_mm", "y_mm", "z_mm", "power_mod", "param"])
        w.writerows(hatch_rows(s["speed"], s["offset"]))
    cfg["path"] = {"file": path_file.name}

    depths = np.arange(0.0, Z_MAX + 1e-9, DZ_FINE)
    cfg["mode_settings"]["t_history"]["probe_points"] = \
        [[0.0, 0.0, -float(round(d, 9))] for d in depths]
    cfg["output"]["directory"] = str(OUT_DIR.relative_to(ROOT))

    cfg_file = CFG_DIR / f"config_{name}.yaml"
    header = (f"# Generated by tools/vibenite290_layer_history.py — scenario "
              f"'{name}': {s['note']} (VED {ved(s):.0f} J/mm^3)\n")
    cfg_file.write_text(header + yaml.safe_dump(cfg, sort_keys=False),
                        encoding="utf-8")
    return cfg_file


def beam_xy(path, t: float) -> tuple[float, float]:
    for i in range(1, len(path)):
        if t <= path[i].seg_time:
            a, b = path[i - 1], path[i]
            span = b.seg_time - a.seg_time
            f = 0.0 if span <= 0 or b.mode == 1 else (t - a.seg_time) / span
            return a.x + f * (b.x - a.x), a.y + f * (b.y - a.y)
    return path[-1].x, path[-1].y


def run_history(sim) -> tuple[np.ndarray, np.ndarray]:
    """Adaptive time stepping: fine while the beam is near the probe column."""
    integ = Integrator(sim)
    probes = np.asarray(sim.param.probe_points, dtype=np.float64)
    px, py, pz = probes[:, 0], probes[:, 1], probes[:, 2]

    t_end = sim.scan_end_time + T_AFTER
    dt_fine, dt_coarse = 1.0e-4, 5.0e-3
    near = 2.0e-3                                   # m
    t, times, temps = 0.0, [], []
    while t <= t_end:
        nodes = integ.build_nodes(t, is_solidification=False)
        temps.append(calc_temperature(nodes, px, py, pz, sim.material.T_init))
        times.append(t)
        bx, by = beam_xy(sim.path, t)
        close = t < sim.scan_end_time and np.hypot(bx, by) < near
        just_after = 0.0 < t - _last_near(sim.path, t, near) < 0.05
        t += dt_fine if (close or just_after) else dt_coarse
    return np.array(times), np.array(temps)


def _last_near(path, t: float, near: float, _cache={}) -> float:
    """Latest time <= t at which the beam was within `near` of the probe."""
    key = id(path)
    if key not in _cache:
        ts = np.linspace(0, path[-1].seg_time, 20000)
        xy = np.array([beam_xy(path, x) for x in ts])
        _cache[key] = ts[np.hypot(xy[:, 0], xy[:, 1]) < near]
    hits = _cache[key]
    hits = hits[hits <= t]
    return hits[-1] if len(hits) else -1.0


def summarise(name, s, sim, times, temps) -> list[dict]:
    mat = sim.material
    T_b, T_l = mat.T_init, mat.T_liq
    depths = -np.asarray(sim.param.probe_points)[:, 2]
    peaks = temps.max(axis=0)

    melted = depths[peaks >= T_l]
    melt_depth = melted.max() if len(melted) else 0.0

    # Cooling rate through the liquidus at the deepest melted probe
    # (fusion line = last liquid to solidify in this column).
    cr = float("nan")
    if len(melted):
        j = int(np.where(depths == melt_depth)[0][0])
        T = temps[:, j]
        ipk = int(T.argmax())
        k = ipk + int(np.argmax(T[ipk:] < T_l))
        if k > ipk:
            cr = (T[k - 1] - T[k]) / (times[k] - times[k - 1])

    rows = []
    n_layers = int(round(Z_MAX / LAYER_T))
    for n in range(n_layers + 1):
        j = int(np.argmin(np.abs(depths - n * LAYER_T)))
        T = temps[:, j]
        ipk = int(T.argmax())
        half = T_b + 0.5 * (T[ipk] - T_b)
        above = times[T >= half]
        fwhm = above[-1] - above[0] if len(above) > 1 else 0.0
        rows.append(dict(layer_above=n, depth_mm=depths[j] * 1e3,
                         T_peak_C=T[ipk] - 273.15, t_peak_s=times[ipk],
                         fwhm_s=fwhm, remelted=bool(T[ipk] >= T_l)))

    n_remelt = max(r["layer_above"] for r in rows if r["remelted"]) \
        if any(r["remelted"] for r in rows) else -1
    print(f"\n=== {name}: {s['note']} | P={s['power']:.0f} W, "
          f"v={s['speed']:.0f} mm/s, h={s['offset']} mm, VED={ved(s):.0f} J/mm3")
    print(f"  melt-pool depth ~ {melt_depth * 1e3:.2f} mm "
          f"-> remelted by the next {max(n_remelt, 0)} layer(s)")
    print(f"  cooling rate at liquidus (fusion line) ~ {cr:.3g} K/s")
    print("  layer_above  depth_mm  T_peak_C  FWHM_ms  remelted")
    for r in rows:
        print(f"  {r['layer_above']:>11d}  {r['depth_mm']:8.2f}  "
              f"{r['T_peak_C']:8.0f}  {r['fwhm_s'] * 1e3:7.1f}  {r['remelted']}")

    with open(OUT_DIR / f"{name}_spikes.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    hdr = "time_s " + " ".join(f"T_K_z{d * 1e3:.2f}mm" for d in depths)
    np.savetxt(OUT_DIR / f"{name}_T_history.csv",
               np.column_stack([times, temps]), header=hdr, comments="",
               fmt="%.6e")
    return rows


def main(names: list[str]) -> None:
    CFG_DIR.mkdir(parents=True, exist_ok=True)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name in names or SCENARIOS:
        s = SCENARIOS[name]
        cfg_file = write_scenario_files(name, s)
        sim = load_config(str(cfg_file))
        times, temps = run_history(sim)
        summarise(name, s, sim, times, temps)


if __name__ == "__main__":
    main(sys.argv[1:])
